#!/usr/bin/env python3
"""Resolve the certificate of record, and refuse if the artifacts disagree with it.

Usage:
    python3 pipeline/certref.py            # prints the repo-relative path, or exits non-zero
    python3 pipeline/certref.py --q 10     # the highest verified certificate at q=10

Nothing names the certificate of record in more than one place. `manifest/make_bundle.sh` and
`pipeline/manifest.py` both ask here, so a new certificate is adopted by regenerating the two
parameter files, never by editing a file list.

"Of record" is not "newest by timestamp", which a checkout or a `touch` can reorder. It is the
highest verified bound in results/, and the paper and the Lean development must both have been
generated from that same file:

  1. among results/*cert*.json, keep the ones whose local_certificate.verified is true, and
     take the one with the greatest certified bound;
  2. paper/certdata.tex records the certificate paper/certdata.py read;
  3. lean/SimpleZeros/Params.lean records the certificate tools/params_from_cert.py read.

If (2) or (3) names anything but (1), the paper or Lean is built against a superseded
certificate and this exits non-zero rather than let a bundle ship the mismatch. The fix is
always to regenerate, never to edit this file.
"""
import json
import pathlib
import re
import sys
from decimal import Decimal

CERTDATA = "paper/certdata.tex"
PARAMS = "lean/SimpleZeros/Params.lean"


def _floor(d):
    """The certified bound, preferring the exact decimal floor over the float."""
    fp = d.get("final_projection", {})
    cl = fp.get("certified_lower_bound")
    if cl and "decimal_floor" in cl:
        return Decimal(str(cl["decimal_floor"]))
    if "computed_bound" in fp:
        return Decimal(repr(fp["computed_bound"]))
    return None


def _declared(root, rel, pattern):
    """The certificate path a generated file records in its header."""
    path = root / rel
    if not path.exists():
        sys.exit(f"{rel} is missing; regenerate it before resolving the certificate of record")
    m = re.search(pattern, path.read_text())
    if not m:
        sys.exit(f"{rel} does not record which certificate generated it; regenerate it")
    return m.group(1)


def cert_of_record(root=pathlib.Path(".")):
    root = pathlib.Path(root)
    best, best_floor, ties = None, None, []
    for p in sorted((root / "results").glob("*cert*.json")):
        try:
            d = json.loads(p.read_text())
        except (json.JSONDecodeError, UnicodeDecodeError):
            continue
        if not d.get("local_certificate", {}).get("verified", False):
            continue
        f = _floor(d)
        if f is None:
            continue
        if best_floor is None or f > best_floor:
            best, best_floor, ties = p, f, [p]
        elif f == best_floor:
            ties.append(p)
    if best is None:
        sys.exit("no verified certificate found under results/")
    if len(ties) > 1:
        sys.exit("several verified certificates share the top bound "
                 f"{best_floor}: {', '.join(t.name for t in ties)}; "
                 "remove or supersede all but one")

    rel = best.relative_to(root).as_posix()
    declared = {
        CERTDATA: _declared(root, CERTDATA, r"Generated by paper/certdata\.py from (\S+)"),
        PARAMS: _declared(root, PARAMS, r"certificate:\s*(\S+)"),
    }
    stale = {k: v for k, v in declared.items() if v != rel}
    if stale:
        lines = "\n".join(f"  {k} was generated from {v}" for k, v in stale.items())
        sys.exit(f"the certificate of record is {rel} (bound {best_floor}), but\n{lines}\n"
                 f"Regenerate:\n"
                 f"  python3 paper/certdata.py {rel} && python3 paper/searchdata.py\n"
                 f"  python3 lean/tools/params_from_cert.py {rel}\n"
                 f"then rebuild the paper and run `lake build` in lean/.")
    return rel


def cert_at(root, q):
    """The highest verified certificate at geometry length q, repo-relative.

    The per-length analogue of cert_of_record, without its cross-check: only one
    certificate generates the paper and Lean, while every length has its own row in
    the paper's per-length table and its own reproduction target.
    """
    root = pathlib.Path(root)
    best, best_floor, ties = None, None, []
    for p in sorted((root / "results").glob("*cert*.json")):
        try:
            d = json.loads(p.read_text())
        except (json.JSONDecodeError, UnicodeDecodeError):
            continue
        if d.get("q") != q or not d.get("local_certificate", {}).get("verified", False):
            continue
        f = _floor(d)
        if f is None:
            continue
        if best_floor is None or f > best_floor:
            best, best_floor, ties = p, f, [p]
        elif f == best_floor:
            ties.append(p)
    if best is None:
        sys.exit(f"no verified certificate at q={q} under results/")
    if len(ties) > 1:
        sys.exit(f"several verified q={q} certificates share the top bound {best_floor}: "
                 f"{', '.join(t.name for t in ties)}")
    return best.relative_to(root).as_posix()


if __name__ == "__main__":
    root = pathlib.Path(__file__).resolve().parent.parent
    if len(sys.argv) == 3 and sys.argv[1] == "--q":
        print(cert_at(root, int(sys.argv[2])))
    else:
        print(cert_of_record(root))
